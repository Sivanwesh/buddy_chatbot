start = [180, 0, 90]


def send_data(vals):
    data_str = f"{vals[0]},{vals[1]},{vals[2]}\n"
    arduino.write(data_str.encode('utf-8'))


def move(target, delay=0.01):
    global start
    max_steps = max(abs(target[i] - start[i]) for i in range(3))
    if max_steps == 0:
        return
    for step in range(1, max_steps + 1):
        current = start[:]
        for i in range(3):
            if start[i] < target[i]:
                current[i] = min(start[i] + step, target[i])
            else:
                current[i] = max(start[i] - step, target[i])
        send_data(current)
        time.sleep(delay)
    start = target[:]


def execute_movements(movements_list):
    """Iterates through all movement keyframes generated by Gemini."""
    for keyframe in movements_list:
        if isinstance(keyframe, list) and len(keyframe) == 3:
            move(keyframe)
            time.sleep(0.15)  # Brief pause between keyframe targets


def hello():
    global start
    print("Waving...")
    move([start[0], 180, start[2]])
    for _ in range(3):
        move([start[0], 150, start[2]])
        move([start[0], 180, start[2]])
    move([start[0], 0, start[2]])
    print("Done waving.")


