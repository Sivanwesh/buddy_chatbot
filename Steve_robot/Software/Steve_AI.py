def conversation_loop():
    # Configure Gemini to act as a motor controller that outputs JSON
    chat_config = types.GenerateContentConfig(
        system_instruction=SYSTEM_INSTRUCTION,
        response_mime_type="application/json",
    )

    chat = client.chats.create(model="gemini-3.6-flash", config=chat_config)
    print("--- Dynamic Motor Controller Active ---")

    while True:
        text = listen_once("Listening for your question...")

        if text is None:
            continue

        if STOP_WORD in text:
            print("Stopping conversation. Say the wake word to start again.")
            hello()
            text_to_speech("Okay, going back to sleep.")
            break

        if NEW_CHAT_WORD in text:
            print("Clearing memory and starting a new chat...")
            chat = client.chats.create(model="gemini-3.6-flash", config=chat_config)
            text_to_speech("Memory cleared. Starting a new chat.")
            continue

        try:
            response = chat.send_message(text)

            # Convert Gemini's text response into a Python dictionary
            data = json.loads(response.text)

            # Extract the speech and movements from the JSON
            speech_text = data.get("speech", "")
            movements = data.get("movements", [])

            print(f"Gemini: {speech_text}")
            print(f"Keyframes generated: {movements}")

            # 1. Speak the text
            text_to_speech(speech_text)

            # 2. Execute the dynamic movements
            execute_movements(movements)

        except json.JSONDecodeError:
            print("Error: Gemini output was not valid JSON.")
            text_to_speech("I had an internal processing error.")
        except Exception as e:
            print(f"Error with Gemini API: {e}")
            text_to_speech("Sorry, I had trouble connecting to my brain.")


